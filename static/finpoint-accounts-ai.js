/* LHM Ads AI: multi-account cards, account shortcuts, transparent AI Center.
   Dashboard data is always supplied by local authenticated endpoints. */
'use strict';
(()=>{
 const $=id=>document.getElementById(id);
 const page=name=>document.querySelector('[data-page="'+name+'"]');
 const connected=a=>['google','meta'].includes(a.platform)&&a.connected&&!String(a.label).startsWith('[REVOKED]');
 let busy=false,accounts=[];
 function initAccounts(){
   const host=$('page-accounts'),before=$('oauth-connect-panel');
   if(!host||!before||$('fp-accounts-head'))return;
   const el=document.createElement('section');el.className='fp-accounts-head';el.id='fp-accounts-head';
   el.innerHTML='<article><span>ĐÃ THÊM</span><strong id="fp-accounts-all">—</strong><small>Không bao gồm token đã thu hồi</small></article>'+
    '<article><span>GOOGLE ADS</span><strong id="fp-accounts-google">—</strong><small>Kiểm tra quyền riêng</small></article>'+
    '<article><span>META ADS</span><strong id="fp-accounts-meta">—</strong><small>Kiểm tra quyền riêng</small></article>'+
    '<article><span>ĐÃ LƯU TOKEN</span><strong id="fp-accounts-connected">—</strong><small>Không có nghĩa API còn hoạt động</small></article>';
   before.before(el);
   const foot=document.createElement('p');foot.id='fp-account-note';foot.className='fp-account-note';
   foot.textContent='Quyền kết nối phải được kiểm tra qua API; không dùng chung token giữa khách hàng.';
   $('accounts-table')?.before(foot);
 }
 async function refreshAccounts(){
   if(busy||!$('page-accounts')||$('page-accounts').classList.contains('hidden'))return;
   busy=true;
   try{
    accounts=await api('/api/accounts');
    const valid=accounts.filter(a=>!String(a.label).startsWith('[REVOKED]'));
    const counters={all:valid.length,google:valid.filter(a=>a.platform==='google').length,meta:valid.filter(a=>a.platform==='meta').length,connected:valid.filter(connected).length};
    Object.entries(counters).forEach(([key,n])=>{const x=$('fp-accounts-'+key);if(x)x.textContent=String(n)});
    // Only annotate rows already generated by the existing secure UI.
    accounts.forEach((acc,index)=>{
      const tr=document.querySelectorAll('#accounts-table tbody tr')[index];if(!tr||!connected(acc))return;
      const cell=tr.lastElementChild;if(!cell||cell.querySelector('[data-fp-campaign]'))return;
      const button=document.createElement('button');button.type='button';button.className='small-btn fp-account-shortcut';
      button.textContent='Chiến dịch';button.dataset.fpCampaign=String(acc.id);
      button.title='Xem chiến dịch của tài khoản (chỉ đọc)';
      cell.append(button);
      if(typeof isAdmin==='function'&&isAdmin()){
        const b=document.createElement('button');b.type='button';b.className='small-btn fp-account-shortcut';
        b.textContent='Autopilot';b.dataset.fpAutopilot=String(acc.id);
        b.title='Mở kế hoạch thay đổi có phê duyệt';cell.append(b);
      }
    });
   }catch(e){$('fp-account-note').textContent='Chưa đọc được danh sách tài khoản: '+String(e.message||e)}
   finally{busy=false}
 }
 function gotoAccount(name,id){
   const nav=page(name);if(!nav)return;
   nav.click();
   const picker=name==='campaigns'?'opt-account':'ap-account';
   const attempt=()=>{const s=$(picker);if(s&&[...s.options].some(x=>x.value===String(id)))s.value=String(id)};
   for(const delay of [180,550,1100])setTimeout(attempt,delay);
 }
 function initAI(){
   const panel=$('page-assistant');if(!panel||$('fp-ai-hub'))return;
   const hub=document.createElement('section');hub.className='fp-ai-hub';hub.id='fp-ai-hub';
   hub.innerHTML='<article class="fp-ai-state"><div class="fp-ai-title"><span class="fp-ai-mark">✧</span><div><h3>AI Intelligence Center</h3><p class="muted tiny">Phân tích và tư vấn, không tự chi tiền quảng cáo.</p></div></div>'+
    '<div class="fp-ai-row"><div><small>Chế độ AI</small><strong id="fp-ai-mode">Đang kiểm tra…</strong></div><div><small>Model</small><strong id="fp-ai-model">—</strong></div><div><small>Hạn mức UTC hôm nay</small><strong id="fp-ai-usage">—</strong></div></div>'+
    '<p class="fp-ai-disclosure" id="fp-ai-disclosure">Trạng thái API hiển thị sau khi đăng nhập.</p>'+
    '<button type="button" id="fp-ai-refresh" class="btn secondary">↻ Kiểm tra trạng thái</button> <button type="button" id="fp-ai-config" class="btn secondary">⚙ Cấu hình OpenRouter</button></article>'+
    '<article class="fp-ai-workflows"><h3>Chọn tác vụ phân tích</h3><p class="muted tiny">Chỉ điền câu hỏi. Phần mềm gửi cho AI khi anh bấm Gửi.</p>'+
    '<div class="fp-ai-prompt-grid">'+
    '<button type="button" data-fp-prompt="Phân tích hiệu suất quảng cáo 7 ngày, chỉ kết luận theo dữ liệu có thật.">◎ Hiệu suất</button>'+
    '<button type="button" data-fp-prompt="Kiểm tra dấu hiệu chi tiêu lãng phí và các số liệu cần đối chứng trước khi đổi ngân sách.">◈ Ngân sách</button>'+
    '<button type="button" data-fp-prompt="Gợi ý cách nghiên cứu từ khóa phủ định an toàn, tránh chặn từ khóa có chuyển đổi.">⌕ Từ khóa</button>'+
    '<button type="button" data-fp-prompt="Giải thích rủi ro khi chuyển chiến lược giá thầu tự động của Google Ads.">↗ Chiến lược giá thầu</button></div></article>';
   panel.querySelector('.chat-panel')?.before(hub);
   $('fp-ai-refresh').addEventListener('click',refreshAI);
   $('fp-ai-config').addEventListener('click',()=>page('settings')?.click());
   hub.addEventListener('click',e=>{const b=e.target.closest('[data-fp-prompt]');if(!b)return;
      const input=$('chat-input');if(input){input.value=b.dataset.fpPrompt;input.focus();}
   });
 }
 async function refreshAI(){
   if(!$('fp-ai-mode')||$('page-assistant').classList.contains('hidden'))return;
   try{const r=await api('/api/ai/settings');
     $('fp-ai-mode').textContent=r.enabled?'OpenRouter được bật':'Phân tích nội bộ';
     $('fp-ai-model').textContent=r.enabled?(r.model||'Chưa chọn'):'Không gọi dịch vụ ngoài';
     $('fp-ai-usage').textContent=r.enabled?String(r.used_today||0)+' / '+String(r.daily_limit||30):'Không áp dụng';
     $('fp-ai-disclosure').textContent=r.enabled?'Khi bấm Gửi, câu hỏi và số liệu tổng hợp sẽ gửi cho OpenRouter, có thể phát sinh phí API. Không tự thực thi lệnh quảng cáo.':'OpenRouter đang tắt. Phân tích thực hiện trên máy; token không được đưa vào câu hỏi gửi đi.';
   }catch(e){$('fp-ai-mode').textContent='Chưa xác minh';$('fp-ai-disclosure').textContent=String(e.message||e)}
 }
 document.addEventListener('DOMContentLoaded',()=>{
   initAccounts();initAI();
   document.addEventListener('lhm:accounts-loaded',()=>setTimeout(refreshAccounts,0));
   page('accounts')?.addEventListener('click',()=>setTimeout(refreshAccounts,350));
   $('refresh-accounts')?.addEventListener('click',()=>setTimeout(refreshAccounts,450));
   $('accounts-table')?.addEventListener('click',e=>{
     const b=e.target.closest('[data-fp-campaign],[data-fp-autopilot]');if(!b)return;
     if(b.dataset.fpCampaign)gotoAccount('campaigns',b.dataset.fpCampaign);
     else if(b.dataset.fpAutopilot&&typeof isAdmin==='function'&&isAdmin())gotoAccount('autopilot',b.dataset.fpAutopilot);
   });
   page('assistant')?.addEventListener('click',()=>setTimeout(refreshAI,100));
 });
})();